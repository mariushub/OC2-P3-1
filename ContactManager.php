<?php

/**
 * Holds every SQL query on the contact table.
 */
class ContactManager
{
    private PDO $pdo;

    public function __construct()
    {
        $this->pdo = (new DBConnect())->getPDO();
    }

    public function findAll(): array
    {
        // No user input in this query, so a simple query() is safe
        $request = $this->pdo->query('SELECT * FROM contact');
        $rows = $request->fetchAll(PDO::FETCH_ASSOC);
        $contacts = [];

        foreach ($rows as $row) {
            $contacts[] = $this->createContactFromRow($row);
        }

        return $contacts;
    }

    public function findById(int $id): ?Contact
    {
        // Prepared statement: the id is sent separately, so SQL injection is not possible
        $request = $this->pdo->prepare('SELECT * FROM contact WHERE id = :id');
        $request->execute(['id' => $id]);
        $row = $request->fetch(PDO::FETCH_ASSOC);

        // No contact with this id
        if ($row === false) {
            return null;
        }

        return $this->createContactFromRow($row);
    }

    public function create(Contact $contact): Contact
    {
        $request = $this->pdo->prepare(
            'INSERT INTO contact (name, email, phone) VALUES (:name, :email, :phone)'
        );
        $request->execute([
            'name' => $contact->getName(),
            'email' => $contact->getEmail(),
            'phone' => $contact->getPhone(),
        ]);

        // Gets the id generated by the database
        $contact->setId((int) $this->pdo->lastInsertId());

        return $contact;
    }

    // Turns a table row into a Contact object 
    private function createContactFromRow(array $row): Contact
    {
        $contact = new Contact();
        $contact->setId($row['id']);
        $contact->setName($row['name']);
        $contact->setEmail($row['email']);
        $contact->setPhone($row['phone']);

        return $contact;
    }

    public function delete(int $id): bool
    {
        $request = $this->pdo->prepare('DELETE FROM contact WHERE id = :id');
        $request->execute(['id' => $id]);

        // 0 deleted rows means the id did not exist
        return $request->rowCount() > 0;
    }
}
